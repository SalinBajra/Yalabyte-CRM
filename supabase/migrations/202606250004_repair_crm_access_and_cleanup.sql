set data = jsonb_set(data, '{owner}', '""'::jsonb, true)
where coalesce(data ->> 'owner', '') <> ''
  and not exists (
    select 1
    from public.team_members
    where lower(trim(name)) = lower(trim(public.leads.data ->> 'owner'))
  );
