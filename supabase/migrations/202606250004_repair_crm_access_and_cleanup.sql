-- Safe to run more than once. Use this when older CRM migrations were applied
-- partially or Supabase reports that policies already exist.

create table if not exists public.team_members (
  user_id uuid primary key references auth.users(id) on delete cascade,
  name text not null,
  email text not null unique,
  last_seen_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

alter table public.team_members
add column if not exists role text not null default 'member',
add column if not exists phone text not null default '',
add column if not exists bio text not null default '',
add column if not exists status text not null default 'available',
add column if not exists avatar_url text not null default '';

alter table public.team_members drop constraint if exists team_members_role_check;
alter table public.team_members
add constraint team_members_role_check check (role in ('admin', 'finance', 'member'));

alter table public.team_members drop constraint if exists team_members_status_check;
alter table public.team_members
add constraint team_members_status_check check (status in ('available', 'busy', 'away', 'offline'));

alter table public.team_members enable row level security;

drop policy if exists "YalaByte team can view team members" on public.team_members;
create policy "YalaByte team can view team members"
on public.team_members for select to authenticated
using (lower(coalesce(auth.jwt() ->> 'email', '')) like '%@yalabyte.com');

drop policy if exists "Team members can register themselves" on public.team_members;
create policy "Team members can register themselves"
on public.team_members for insert to authenticated
with check (
  user_id = auth.uid()
  and lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  and lower(email) like '%@yalabyte.com'
);

drop policy if exists "Team members can update themselves" on public.team_members;
create policy "Team members can update themselves"
on public.team_members for update to authenticated
using (user_id = auth.uid())
with check (
  user_id = auth.uid()
  and lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  and lower(email) like '%@yalabyte.com'
);

grant select, insert, update on public.team_members to authenticated;
revoke insert, update on public.team_members from authenticated;
grant insert (user_id, name, email, last_seen_at) on public.team_members to authenticated;
grant update (name, email, phone, bio, status, avatar_url, last_seen_at) on public.team_members to authenticated;

do $$ begin
  create type public.app_role as enum ('admin', 'finance', 'member');
exception when duplicate_object then null;
end $$;

alter type public.app_role add value if not exists 'finance';

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique check (lower(email) like '%@yalabyte.com'),
  full_name text,
  role public.app_role not null default 'member',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.profiles enable row level security;

drop policy if exists "Users can read their own shared profile" on public.profiles;
create policy "Users can read their own shared profile"
on public.profiles for select to authenticated
using (id = auth.uid());

drop policy if exists "Users can create their own member profile" on public.profiles;
create policy "Users can create their own member profile"
on public.profiles for insert to authenticated
with check (
  id = auth.uid()
  and lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  and role = 'member'
);

drop policy if exists "Users can refresh their own shared profile" on public.profiles;
create policy "Users can refresh their own shared profile"
on public.profiles for update to authenticated
using (id = auth.uid())
with check (
  id = auth.uid()
  and lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
);

grant select on public.profiles to authenticated;
grant insert (id, email, full_name, updated_at) on public.profiles to authenticated;
grant update (email, full_name, updated_at) on public.profiles to authenticated;

