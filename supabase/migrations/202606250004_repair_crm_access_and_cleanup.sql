create or replace function public.current_user_role()
returns public.app_role
language sql
stable
security definer
set search_path = public
as $$ select role from public.profiles where id = auth.uid() $$;

create or replace function public.assign_first_crm_admin()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if not exists (select 1 from public.team_members where role = 'admin') then
    new.role := 'admin';
  elsif new.role not in ('finance', 'member') then
    new.role := 'member';
  end if;
  return new;
end;
$$;

drop trigger if exists assign_first_crm_admin_trigger on public.team_members;
create trigger assign_first_crm_admin_trigger
before insert on public.team_members
for each row execute function public.assign_first_crm_admin();

create or replace function public.set_team_member_role(p_user_id uuid, p_role text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_role not in ('admin', 'finance', 'member') then
    raise exception 'Invalid team role.';
  end if;
  if not exists (
    select 1 from public.team_members
    where user_id = auth.uid() and role = 'admin'
  ) then
    raise exception 'Only CRM admins can change team roles.';
  end if;
  if p_user_id = auth.uid() and p_role <> 'admin' and (
    select count(*) from public.team_members where role = 'admin'
  ) = 1 then
    raise exception 'The CRM must retain at least one admin.';
  end if;

  update public.team_members
  set role = p_role
  where user_id = p_user_id;

  insert into public.profiles (id, email, full_name, role)
  select user_id, lower(email), name, p_role::public.app_role
  from public.team_members
  where user_id = p_user_id
  on conflict (id) do update
  set email = excluded.email,
      full_name = excluded.full_name,
      role = excluded.role,
      updated_at = now();
end;
$$;

revoke all on function public.set_team_member_role(uuid, text) from public;
grant execute on function public.set_team_member_role(uuid, text) to authenticated;

insert into public.profiles (id, email, full_name, role)
select
  user_id,
  lower(email),
  name,
  case when role in ('admin', 'finance') then role else 'member' end::public.app_role
from public.team_members
on conflict (id) do update
set email = excluded.email,
    full_name = excluded.full_name,
    role = excluded.role,
    updated_at = now();

