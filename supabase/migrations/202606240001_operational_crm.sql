create or replace function public.set_team_member_role(p_user_id uuid, p_role text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_role not in ('admin', 'member') then
    raise exception 'Invalid team role.';
  end if;
  if not exists (
    select 1 from public.team_members
    where user_id = auth.uid() and role = 'admin'
  ) then
    raise exception 'Only CRM admins can change team roles.';
  end if;
  if p_user_id = auth.uid() and p_role <> 'admin' and (
    select count(*) from public.team_members where role = 'admin'
  ) = 1 then
    raise exception 'The CRM must retain at least one admin.';
  end if;
  update public.team_members set role = p_role where user_id = p_user_id;
end;
$$;

revoke all on function public.set_team_member_role(uuid, text) from public;
grant execute on function public.set_team_member_role(uuid, text) to authenticated;

create or replace function public.delete_crm_lead(p_lead_id text, p_actor_name text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_lead_data jsonb;
  v_actor_email text;
begin
  v_actor_email := lower(coalesce(auth.jwt() ->> 'email', ''));
  if v_actor_email not like '%@yalabyte.com' then
    raise exception 'Only YalaByte team members can delete leads.';
  end if;
  if not exists (
    select 1 from public.team_members
    where user_id = auth.uid() and role = 'admin'
  ) then
    raise exception 'Only CRM admins can delete leads.';
  end if;

  select data into v_lead_data from public.leads where id = p_lead_id for update;
  if v_lead_data is null then raise exception 'Lead not found.'; end if;

  insert into public.lead_deletion_notifications (
    lead_id, lead_name, lead_data, deleted_by, deleted_by_name, deleted_by_email
  ) values (
    p_lead_id,
    coalesce(v_lead_data ->> 'name', 'Unnamed lead'),
    v_lead_data,
    auth.uid(),
    coalesce(nullif(trim(p_actor_name), ''), split_part(v_actor_email, '@', 1)),
    v_actor_email
  );
  delete from public.leads where id = p_lead_id;
end;
$$;

