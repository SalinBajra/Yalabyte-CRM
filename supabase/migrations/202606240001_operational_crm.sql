update public.team_members
set role = 'admin'
where user_id = (
  select user_id from public.team_members order by created_at asc limit 1
)
and not exists (select 1 from public.team_members where role = 'admin');

create or replace function public.assign_first_crm_admin()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if not exists (select 1 from public.team_members where role = 'admin') then
    new.role := 'admin';
  else
    new.role := 'member';
  end if;
  return new;
end;
$$;

drop trigger if exists assign_first_crm_admin_trigger on public.team_members;
create trigger assign_first_crm_admin_trigger
before insert on public.team_members
for each row execute function public.assign_first_crm_admin();

